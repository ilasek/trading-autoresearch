"""Data layer: Parquet store loader + throttled Stooq/Yahoo fetchers.

Research code must only use the loaders (load_universe, load_prices). The fetchers
are for scripts/seed_data.py and scripts/update_data.py — never call them from a
strategy or during an experiment.
"""

from __future__ import annotations

import io
import time
from contextlib import contextmanager
from pathlib import Path

import pandas as pd
import requests
import yaml

ROOT = Path(__file__).resolve().parent.parent
STORE = ROOT / "data" / "store"
UNIVERSE_FILE = ROOT / "data" / "universe.yaml"
# Every priced instrument that was ever a member of a tracked index, plus the
# ETFs. WHEN each stock is eligible is decided by data/membership/intervals.csv,
# not by presence in this file. Generated by scripts/build_membership.py.
UNIVERSE_PIT_FILE = ROOT / "data" / "universe_pit.yaml"
UNIVERSES = {"legacy": UNIVERSE_FILE, "pit": UNIVERSE_PIT_FILE}

OHLCV_COLS = ["open", "high", "low", "close", "volume"]

_STOOQ_URL = "https://stooq.com/q/d/l/?s={symbol}&i=d"
_MIN_REQUEST_INTERVAL = 1.2  # seconds between Stooq requests
_last_request_ts = 0.0


class RateLimitError(RuntimeError):
    """Raised when a data provider signals we exceeded its limits."""


# ---------------------------------------------------------------------------
# Universe
# ---------------------------------------------------------------------------

_ACTIVE = {"universe": "legacy"}


@contextmanager
def using_universe(name: str):
    """Make `name` the universe that `load_universe()` / `instruments()` answer
    for, for the duration of the block. The protocol wraps a strategy call in
    this so a strategy's own `instruments()` lookups see the same universe as
    the price columns it was handed."""
    if name not in UNIVERSES:
        raise ValueError(f"unknown universe {name!r}; one of {sorted(UNIVERSES)}")
    prev = _ACTIVE["universe"]
    _ACTIVE["universe"] = name
    try:
        yield
    finally:
        _ACTIVE["universe"] = prev


def active_universe() -> str:
    return _ACTIVE["universe"]


def load_universe(name: str | None = None) -> dict:
    """Full parsed universe file: {'fx': {...}, 'instruments': [...]}.

    `name` is "legacy" (data/universe.yaml, today's constituents: the v1
    universe) or "pit" (data/universe_pit.yaml); None means the active one."""
    with open(UNIVERSES[name or _ACTIVE["universe"]]) as f:
        return yaml.safe_load(f)


def instruments(
    types: tuple[str, ...] = ("stock", "etf"), universe: str | None = None
) -> list[dict]:
    return [i for i in load_universe(universe)["instruments"] if i["type"] in types]


def instrument_types(universe: str | None = None) -> dict[str, str]:
    """{id: type} for every instrument of a universe."""
    return {i["id"]: i["type"] for i in load_universe(universe)["instruments"]}


def instrument_regions(universe: str | None = None) -> dict[str, str]:
    """{id: listing region} for every instrument of a universe."""
    return {i["id"]: i.get("region", "") for i in load_universe(universe)["instruments"]}


# The cash rate. Protocol v3 pays it on uninvested cash and measures Sharpe on
# returns in excess of it. ^IRX is the 13-week US T-bill discount yield in
# percent; it is fetched by the data-refresh workflow like any other series and
# stored under `id`. Not a universe member: it is never in `prices`.
RATE_SERIES = {"id": "RATE_US3M", "yahoo": "^IRX", "stooq": None, "type": "rate",
               "currency": "USD", "name": "US 13-week T-bill yield (%)"}


def all_series(universe: str | None = None) -> list[dict]:
    """Every series we store for a universe: instruments, FX pairs and the
    cash rate."""
    uni = load_universe(universe)
    fx = [dict(v, type="fx", currency="USD") for v in uni["fx"].values()]
    return uni["instruments"] + fx + [dict(RATE_SERIES)]


# ---------------------------------------------------------------------------
# Store I/O
# ---------------------------------------------------------------------------
#
# Layout: data/store/<YYYY>/<YYYY-MM>.parquet, one long-format file per calendar
# month holding every series' bars for that month (columns: id, date, open,
# high, low, close, volume). The daily refresh therefore rewrites only the
# current month's file, and a closed month never changes again — the repo no
# longer re-commits every series' full history each day. The whole store is
# read once per process and cached; `load_ohlcv` serves slices of that cache.

_STORE_CACHE: dict = {"sig": None, "series": {}}


def store_path(series_id: str | None = None, month: pd.Timestamp | None = None) -> Path:
    """The month file holding `month` (series_id is accepted for backward
    compatibility and ignored: a month file holds every series)."""
    if month is None:
        return STORE
    m = pd.Timestamp(month)
    return STORE / f"{m.year:04d}" / f"{m.year:04d}-{m.month:02d}.parquet"


def _month_files() -> list[Path]:
    return sorted(STORE.glob("[0-9][0-9][0-9][0-9]/[0-9][0-9][0-9][0-9]-[0-9][0-9].parquet"))


def _store_signature(files: list[Path]) -> tuple:
    return tuple((f.name, f.stat().st_mtime_ns, f.stat().st_size) for f in files)


def _read_month(path: Path) -> pd.DataFrame:
    df = pd.read_parquet(path)
    df["date"] = pd.to_datetime(df["date"]).astype("datetime64[ms]")
    return df


def _store_series() -> dict[str, pd.DataFrame]:
    """{series id: date-indexed OHLCV frame} for the whole store.

    Read once per process and cached; `write_many` invalidates the cache, and
    `reload_store()` forces a re-read after an outside change."""
    if _STORE_CACHE["sig"] is not None:
        return _STORE_CACHE["series"]
    files = _month_files()
    sig = _store_signature(files)
    if _STORE_CACHE["sig"] == sig:
        return _STORE_CACHE["series"]
    series: dict[str, pd.DataFrame] = {}
    if files:
        long = pd.concat([_read_month(f) for f in files], ignore_index=True)
        long = long.sort_values(["id", "date"], kind="stable")
        for sid, g in long.groupby("id", sort=False):
            frame = g.set_index("date")[OHLCV_COLS]
            frame.index.name = "Date"
            series[str(sid)] = frame
    _STORE_CACHE.update(sig=sig, series=series)
    return series


def reload_store() -> None:
    _STORE_CACHE["sig"] = None


def store_ids() -> list[str]:
    return sorted(_store_series())


def load_ohlcv(series_id: str) -> pd.DataFrame | None:
    """One series as a date-indexed OHLCV frame, or None if not in the store."""
    df = _store_series().get(series_id)
    return None if df is None else df.copy()


def write_many(frames: dict[str, pd.DataFrame], replace: bool = False) -> None:
    """Merge rows for many series into the store in one pass.

    Idempotent: dedupes on (id, date), keeping the newest row. `replace=True`
    drops a series' existing rows first (a full re-seed). Only the month files
    that receive rows (or lose them, on replace) are rewritten."""
    parts = []
    for sid, df in frames.items():
        if df is None or df.empty:
            continue
        if isinstance(df.columns, pd.MultiIndex):
            raise ValueError(f"{sid}: OHLCV frame has MultiIndex columns {list(df.columns)[:3]}; "
                             f"expected flat {OHLCV_COLS}")
        d = df.copy()
        d.index = pd.to_datetime(d.index).astype("datetime64[ms]")
        for col in OHLCV_COLS:
            if col not in d.columns:
                d[col] = float("nan")
        d = d[OHLCV_COLS].astype(float)
        d = d[~d.index.duplicated(keep="last")]
        d.insert(0, "id", sid)
        parts.append(d.rename_axis("date").reset_index())
    if not parts and not replace:
        return
    new = pd.concat(parts, ignore_index=True) if parts else pd.DataFrame(
        {"date": pd.Series(dtype="datetime64[ms]"), "id": pd.Series(dtype=object),
         **{c: pd.Series(dtype=float) for c in OHLCV_COLS}})
    months = set(new["date"].dt.to_period("M")) if len(new) else set()
    if replace:
        ids = set(frames)
        cached = _store_series()
        for sid in ids:
            old = cached.get(sid)
            if old is not None and len(old):
                months |= set(old.index.to_period("M"))
    for per in sorted(months):
        path = store_path(month=per.to_timestamp())
        chunk = new[new["date"].dt.to_period("M") == per]
        if path.exists():
            old = _read_month(path)
            if replace:
                old = old[~old["id"].isin(set(frames))]
            chunk = pd.concat([old, chunk[old.columns]], ignore_index=True)
        chunk = chunk.drop_duplicates(["id", "date"], keep="last")
        chunk = chunk.sort_values(["id", "date"]).reset_index(drop=True)
        chunk = chunk[["id", "date", *OHLCV_COLS]]
        path.parent.mkdir(parents=True, exist_ok=True)
        if chunk.empty:
            path.unlink(missing_ok=True)
        else:
            chunk.to_parquet(path, index=False, compression="zstd")
    _STORE_CACHE["sig"] = None


def write_ohlcv(series_id: str, df: pd.DataFrame, replace: bool = False) -> None:
    """Merge new rows for one series into the store (see `write_many`)."""
    write_many({series_id: df}, replace=replace)


def last_date(series_id: str) -> pd.Timestamp | None:
    df = _store_series().get(series_id)
    return None if df is None or df.empty else df.index[-1]


