def _fx_to_usd(currency: str, universe: dict) -> pd.Series:
    """Multiplicative series converting one unit of `currency` to USD."""
    if currency == "USD":
        raise ValueError("no FX needed for USD")
    scale = 1.0
    if currency == "GBX":  # LSE pence
        currency, scale = "GBP", 0.01
    spec = universe["fx"][currency]
    df = load_ohlcv(spec["id"])
    if df is None:
        raise FileNotFoundError(
            f"FX series {spec['id']} missing from store; run scripts/seed_data.py"
        )
    rate = df["close"]
    if spec.get("invert"):
        rate = 1.0 / rate
    return rate * scale


def _raw_panel(
    field: str,
    types: tuple[str, ...],
    universe: dict,
    fx_cache: dict[str, pd.Series],
    convert_fx: bool = True,
) -> pd.DataFrame:
    """One field as a wide frame (dates x instrument ids), sorted, unaligned.

    `convert_fx=False` leaves the series in its native unit — used for volume,
    which is a share count and must not be multiplied by an FX rate.
    """
    cols: dict[str, pd.Series] = {}
    for inst in universe["instruments"]:
        if inst["type"] not in types:
            continue
        df = load_ohlcv(inst["id"])
        if df is None or df.empty:
            continue
        series = df[field].astype(float)
        if inst.get("valid_from"):
            # data before this date failed the builder's quality check
            series = series.loc[inst["valid_from"]:]
        cur = inst["currency"]
        if convert_fx and cur != "USD":
            if cur not in fx_cache:
                fx_cache[cur] = _fx_to_usd(cur, universe)
            fx = fx_cache[cur].reindex(series.index).ffill()
            series = series * fx
        cols[inst["id"]] = series
    if not cols:
        raise FileNotFoundError("data store is empty; run scripts/seed_data.py")
    return pd.DataFrame(cols).sort_index()


def load_prices(
    types: tuple[str, ...] = ("stock", "etf"),
    currency: str = "USD",
    field: str = "close",
    universe: str | None = None,
    start: str | None = None,
) -> pd.DataFrame:
    """Wide frame (dates x instrument ids) of daily prices converted to USD.

    Instruments missing from the store are skipped with a warning column count
    difference; NaN before an instrument's first bar is expected and strategies
    must handle it.
    """
    if currency != "USD":
        raise ValueError("only USD target currency is supported")
    prices = _raw_panel(field, types, load_universe(universe), {})
    if start is not None:
        prices = prices.loc[start:]
    # Drop weekend/garbage rows where nearly nothing traded.
    prices = prices.dropna(how="all")
    # The index is the union of all exchange calendars, so every column has
    # holes on foreign holidays. Forward-fill briefly so rolling windows and
    # returns behave; the cap keeps genuinely dead series NaN (and the engine
    # zeroes weights on NaN prices).
    prices = prices.ffill(limit=10)
    return prices


# Panels a strategy may receive as its optional second argument. `close` is
# omitted: it is `load_prices()`, which the strategy already gets as `prices`.
AUX_FIELDS = ("open", "high", "low", "volume")


def load_panels(
    types: tuple[str, ...] = ("stock", "etf"),
    fields: tuple[str, ...] = AUX_FIELDS,
    universe: str | None = None,
    start: str | None = None,
) -> dict[str, pd.DataFrame]:
    """Auxiliary OHLCV panels aligned to `load_prices()`'s index and columns.

    Every frame shares the close panel's index and column order exactly, so a
    caller can truncate `prices` and the panels by the same slice and know they
    still line up — the property the protocol's causality check depends on.

    - `open`/`high`/`low` are FX-converted to USD like the close, and briefly
      forward-filled on the same 10-day cap, for the same reason.
    - `volume` is a **share count** and is left in native units, un-ffilled: a
      foreign holiday has no volume, and fabricating one would corrupt any
      liquidity measure built on it. Expect NaN there and skip it.
    - `dollar_volume` is close_usd * volume, i.e. USD traded notional — the
      currency-correct input for Amihud-style illiquidity.
    """
    close = load_prices(types=types, universe=universe, start=start)
    uni = load_universe(universe)
    fx_cache: dict[str, pd.Series] = {}
    panels: dict[str, pd.DataFrame] = {}
    for field in fields:
        raw = _raw_panel(field, types, uni, fx_cache, convert_fx=(field != "volume"))
        panel = raw.reindex(index=close.index, columns=close.columns)
        if field != "volume":
            panel = panel.ffill(limit=10)
        panels[field] = panel
    if "volume" in panels:
        panels["dollar_volume"] = panels["volume"] * close
    return panels


def load_traded(
    index: pd.DatetimeIndex, columns, universe: str | None = None,
) -> pd.DataFrame:
    """Bool panel aligned to `load_prices()`: True where the instrument printed
    a real close that day. `load_prices` forward-fills holidays so rolling
    windows behave; an execution model must not fill an order at such a
    stale, carried-forward price."""
    uni = {i["id"]: i for i in load_universe(universe)["instruments"]}
    out = pd.DataFrame(False, index=index, columns=list(columns))
    for col in out.columns:
        df = load_ohlcv(col)
        if df is None or df.empty:
            continue
        close = df["close"]
        valid_from = (uni.get(col) or {}).get("valid_from")
        if valid_from:
            close = close.loc[valid_from:]
        out[col] = close.notna().reindex(index).fillna(False).astype(bool)
    return out


def load_rf(index: pd.DatetimeIndex, required: bool = True) -> pd.Series | None:
    """Daily simple return on cash for each row of `index`, from the stored
    T-bill yield: the yield known at the previous row, accrued over the
    calendar days between the rows (actual/365). The first row accrues
    nothing. Returns None (or raises, if `required`) when the series is not in
    the store yet — the data-refresh workflow seeds it."""
    df = load_ohlcv(RATE_SERIES["id"])
    if df is None or df.empty:
        if required:
            raise FileNotFoundError(
                f"cash-rate series {RATE_SERIES['id']} ({RATE_SERIES['yahoo']}) is not in the "
                f"store; run the data-refresh workflow, which seeds it"
            )
        return None
    yld = df["close"].astype(float).sort_index()
    yld = yld.reindex(yld.index.union(index)).ffill().reindex(index)
    days = pd.Series(index, index=index).diff().dt.days.fillna(0.0)
    rf = (yld.shift(1) / 100.0 * days / 365.0).fillna(0.0)
    return rf.rename("rf")


def slice_panels(panels: dict[str, pd.DataFrame] | None, index) -> dict[str, pd.DataFrame]:
    """Restrict every panel to `index` (a DatetimeIndex, typically a truncated
    price index). The one supported way to narrow a panel dict: doing it by hand
    risks handing a strategy rows its prices cannot see."""
    if not panels:
        return {}
    return {k: v.reindex(index=index) for k, v in panels.items()}


